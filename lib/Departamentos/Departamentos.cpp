int obtenerIndiceDepartamento(const String& nombreDepto) {
String temp = nombreDepto;
  temp.trim();

  for (int i = 0; i < NUM_DEPARTAMENTOS; i++) {
    // temp es String y departamentos[i].nombre es const char*
    if (temp.equalsIgnoreCase(departamentos[i].nombre)) {
      return i;
    }
  }

  return -1;
}